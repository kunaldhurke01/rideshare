import { FareBreakdown } from '../types';

export interface FareCalculationParams {
  primaryDistanceKm: number;
  candidateDistanceKm: number;
  sharedDistanceKm: number;
  detourDistanceKm: number;
  existingPassengersCount?: number;
  newPassengersCount?: number;
}

export interface DynamicFareResult {
  primarySoloFare: number;
  primarySharedFare: number;
  primaryPassengerSavings: number;
  
  candidateSoloFare: number;
  candidateSharedFare: number;
  candidateSavings: number;

  combinedTotalFare: number;
  driverEarnings: number;
  driverBonus: number;
  platformFee: number;

  breakdown: FareBreakdown;
}

// Transparent economic constants
export const FARE_CONFIG = {
  BASE_FLAG_DROP_INR: 60,       // Base pickup fare
  PER_KM_RATE_INR: 15.5,         // Base rate per kilometer
  DETOUR_COMPENSATION_RATE: 12.0,// Compensation paid to driver per detour km
  SHARING_DISCOUNT_FACTOR: 0.35, // 35% discount applied to the shared corridor
  PLATFORM_COMMISSION_PCT: 0.12, // 12% RideShare platform fee
  DRIVER_SHARE_PCT: 0.88         // 88% goes to driver
};

/**
 * Calculates solo ride fare for a given distance in kilometers
 */
export function calculateSoloFare(distanceKm: number): number {
  const base = FARE_CONFIG.BASE_FLAG_DROP_INR;
  const distanceFare = distanceKm * FARE_CONFIG.PER_KM_RATE_INR;
  const total = Math.round(base + distanceFare);
  // Round to nearest 5 for clean currency presentation
  return Math.ceil(total / 5) * 5;
}

/**
 * Smart Fare Redistribution Engine
 * Dynamically calculates fares when passengers share a corridor
 */
export function calculateDynamicFares(params: FareCalculationParams): DynamicFareResult {
  const {
    primaryDistanceKm,
    candidateDistanceKm,
    sharedDistanceKm,
    detourDistanceKm,
    existingPassengersCount = 1,
    newPassengersCount = 1
  } = params;

  // 1. Calculate standard solo fares
  const primarySoloFare = calculateSoloFare(primaryDistanceKm);
  const candidateSoloFare = calculateSoloFare(candidateDistanceKm);

  // 2. Shared corridor economics
  // Cost value of the overlapping highway segment
  const sharedCorridorValue = sharedDistanceKm * FARE_CONFIG.PER_KM_RATE_INR;
  
  // Total discount pool generated by riding together on the same road
  // Pool scales smoothly with number of occupants
  const sharingDiscountPool = sharedCorridorValue * FARE_CONFIG.SHARING_DISCOUNT_FACTOR;

  // Primary passenger gets savings proportional to detour incurred
  // If detour is higher, primary passenger gets additional discount for their patience
  const detourInconvenienceOffset = detourDistanceKm * 4.5;
  const primaryPassengerSavings = Math.round(
    Math.min(
      primarySoloFare * 0.30,
      Math.max(35, (sharingDiscountPool * 0.55) + detourInconvenienceOffset)
    )
  );

  // Joining passenger also gets significant savings over their direct solo fare
  const candidateSavings = Math.round(
    Math.min(
      candidateSoloFare * 0.30,
      Math.max(30, sharingDiscountPool * 0.45)
    )
  );

  // Net passenger fares
  const primarySharedFare = Math.max(80, primarySoloFare - primaryPassengerSavings);
  const candidateSharedFare = Math.max(70, candidateSoloFare - candidateSavings);

  // Combined revenue from all passengers currently in vehicle
  const combinedTotalFare = primarySharedFare + candidateSharedFare;

  // Driver compensation:
  // Driver receives standard base + extra bonus for detour + higher total trip value than solo ride!
  const driverSoloEarnings = primarySoloFare * FARE_CONFIG.DRIVER_SHARE_PCT;
  const detourDriverBonus = Math.round(detourDistanceKm * FARE_CONFIG.DETOUR_COMPENSATION_RATE + 40);
  const driverEarnings = Math.round(driverSoloEarnings + detourDriverBonus);
  const driverBonus = driverEarnings - Math.round(driverSoloEarnings);

  // Sustainable platform commission
  const platformFee = Math.max(30, combinedTotalFare - driverEarnings);

  const breakdown: FareBreakdown = {
    originalSoloFare: primarySoloFare,
    totalBaseFare: FARE_CONFIG.BASE_FLAG_DROP_INR,
    distanceRate: FARE_CONFIG.PER_KM_RATE_INR,
    totalDistanceKm: primaryDistanceKm,
    sharedDistanceKm,
    sharingDiscount: primaryPassengerSavings,
    detourAdjustment: detourDistanceKm,
    platformFee,
    driverEarnings,
    finalPassengerFare: primarySharedFare,
    passengerSavings: primaryPassengerSavings
  };

  return {
    primarySoloFare,
    primarySharedFare,
    primaryPassengerSavings,
    candidateSoloFare,
    candidateSharedFare,
    candidateSavings,
    combinedTotalFare,
    driverEarnings,
    driverBonus,
    platformFee,
    breakdown
  };
}
